import mealsData from "../../data/meals.json";
import type { Meal, Order, OrderInput } from "./types";
import { perMealTarget, priceBreakdown, selectionAverage, selectionCount } from "./plan";
import { getStore } from "./store";

/**
 * The file database.
 *
 * Everything the app persists goes through the four functions at the bottom of
 * this file. They are the only place that touches the filesystem, so swapping
 * to Postgres or Supabase later means rewriting this file and nothing else:
 * keep the signatures, replace the bodies with queries.
 *
 *   data/meals.json   read only catalogue, regenerated by scripts/seed-meals.mjs
 *   data/orders.json  append only, written by the checkout route
 */

/**
 * The menu is bundled at build time rather than read from disk: it only changes
 * when the repository does, and a Worker has no filesystem to read it from.
 */
const MEALS = mealsData as Meal[];

/** No I, O, 0 or 1, so a code read off a screen cannot be mistyped. */
const CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

function makeCode() {
  let out = "";
  for (let i = 0; i < 5; i++) {
    out += CODE_ALPHABET[Math.floor(Math.random() * CODE_ALPHABET.length)];
  }
  return `RTO-${out}`;
}

// ---------------------------------------------------------------------------
// Public API. Replace the bodies below when a real database arrives.
// ---------------------------------------------------------------------------

export async function getMeals(): Promise<Meal[]> {
  return MEALS;
}

export async function getMeal(id: string): Promise<Meal | undefined> {
  const meals = await getMeals();
  return meals.find((m) => m.id === id);
}

export async function listOrders(): Promise<Order[]> {
  return (await getStore()).listOrders();
}

export async function getOrder(code: string): Promise<Order | undefined> {
  return (await getStore()).getOrder(code);
}

export async function createOrder(input: OrderInput): Promise<Order> {
  const meals = await getMeals();
  const count = selectionCount(input.selection);
  const price = priceBreakdown(input.plan, count);
  const avg = selectionAverage(input.selection, meals, input.plan.portion);
  const store = await getStore();

  let code = makeCode();
  while (await store.orderCodeExists(code)) code = makeCode();

  const order: Order = {
    ...input,
    code,
    createdAt: new Date().toISOString(),
    totals: {
      meals: count,
      subtotal: price.subtotal,
      discount: price.discount,
      delivery: price.delivery,
      total: price.total,
      perMealKcal: avg.kcal,
      perMealProtein: avg.protein,
    },
  };

  await store.insertOrder(order);
  return order;
}

/** Used by the checkout route to sanity check what the browser sent. */
export async function validateOrder(input: OrderInput): Promise<string | null> {
  const meals = await getMeals();
  const { plan, selection, customer } = input;

  if (!plan || !selection || !customer) return "Missing plan, selection or customer.";
  if (!["cut", "maintain", "build"].includes(plan.goal)) return "Unknown goal.";
  if (![2, 3].includes(plan.mealsPerDay)) return "Meals per day must be 2 or 3.";
  if (!Number.isFinite(plan.dailyKcal) || plan.dailyKcal < 1200 || plan.dailyKcal > 4500) {
    return "Daily calories out of range.";
  }
  if (!Number.isFinite(plan.days) || plan.days < 1 || plan.days > 21) return "Days out of range.";
  if (!["regular", "large", "xl", "xxl"].includes(plan.portion)) return "Unknown portion size.";

  const expected = plan.days * plan.mealsPerDay;
  const count = selectionCount(selection);
  if (count !== expected) return `Plan needs ${expected} meals, received ${count}.`;
  for (const line of selection) {
    if (!meals.some((m) => m.id === line.mealId)) return `Unknown meal: ${line.mealId}`;
    if (!Number.isInteger(line.qty) || line.qty < 1) return "Invalid quantity.";
  }

  if (!customer.name?.trim()) return "Name is required.";
  if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(customer.email ?? "")) return "A valid email is required.";
  if (!/^\d{4}$/.test(customer.postcode ?? "")) return "Postcode must be four digits.";

  return null;
}

/** Menu wide figures the landing page quotes. Derived, never hand typed. */
export async function menuStats() {
  const meals = await getMeals();
  const n = meals.length || 1;
  const avg = (k: "kcal" | "protein" | "carbs" | "fat") =>
    meals.reduce((s, m) => s + m[k], 0) / n;
  const protein = avg("protein");
  const kcal = avg("kcal");
  return {
    count: meals.length,
    avgProtein: Math.round(protein),
    avgCarbs: Math.round(avg("carbs")),
    avgFat: Math.round(avg("fat")),
    avgKcal: Math.round(kcal),
    proteinPer100Kcal: Math.round((protein / kcal) * 100 * 10) / 10,
    maxCarbs: Math.max(...meals.map((m) => m.carbs)),
    lowCarbCount: meals.filter((m) => m.carbs <= 20).length,
  };
}

